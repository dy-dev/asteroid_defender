# =====================================================================
#  student_rules.py
#
#  Fichier des règles du jeu. Il est vide pour l'instant : c'est normal.
#
#  -------------------------------------------------------------------
#  Comment il fonctionne
#  -------------------------------------------------------------------
#
#  Le jeu relit ce fichier en permanence pendant la partie : une règle
#  enregistrée prend effet aussitôt, sans relancer le jeu.
#
#  Une règle est une condition : elle lit l'état du jeu et, selon ce
#  qu'elle y trouve, donne une valeur à un réglage.
#
#  -------------------------------------------------------------------
#  Où trouver les noms
#  -------------------------------------------------------------------
#
#  Les états du jeu se découvrent dans le jeu. Mettre la partie en
#  pause avec Échap, puis survoler un élément à l'écran : la rubrique
#  « À LIRE dans les règles » donne le nom exact de chaque état et ce
#  qu'il représente.
#
#  Ces états se lisent seulement : leur donner une valeur ici ne change
#  rien à la partie.
#
#  -------------------------------------------------------------------
#  En cas d'erreur
#  -------------------------------------------------------------------
#
#  Une règle mal écrite ne bloque jamais le jeu : il continue avec la
#  dernière version correcte du fichier, jusqu'à la correction.
# =====================================================================
