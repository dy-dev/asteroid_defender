# =====================================================================
#  student_rules.py
#
#  The game rules file. It is empty for now: that is normal.
#
#  -------------------------------------------------------------------
#  How it works
#  -------------------------------------------------------------------
#
#  The game reads this file again and again during play: a saved rule
#  takes effect at once, without restarting the game.
#
#  A rule is a condition: it reads the state of the game and, depending
#  on what it finds, gives a value to a setting.
#
#  -------------------------------------------------------------------
#  Where to find the names
#  -------------------------------------------------------------------
#
#  The game states are discovered in the game. Pause the game with
#  Esc, then hover over an element on screen: the section "TO READ in
#  the rules" gives the exact name of each state and what it stands
#  for.
#
#  These states are read only: giving them a value here changes
#  nothing in the game.
#
#  -------------------------------------------------------------------
#  In case of error
#  -------------------------------------------------------------------
#
#  A badly written rule never blocks the game: it keeps going with the
#  last correct version of the file, until the error is fixed.
# =====================================================================
