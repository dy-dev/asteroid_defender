# =====================================================================
#  student_loops.py
#
#  Fichier des répétitions du jeu. Il est vide pour l'instant : c'est
#  normal.
#
#  -------------------------------------------------------------------
#  Comment il fonctionne
#  -------------------------------------------------------------------
#
#  Chaque bloc correspond à un événement du jeu et commence par une
#  condition sur cet événement, par exemple :  if event == "countdown":
#  Le bloc contient une boucle. Quand l'événement se déclenche, le jeu
#  exécute cette boucle un tour à la fois, étalé dans le temps : l'effet
#  de chaque tour apparaît à l'écran — la valeur du décompte qui change,
#  la jauge qui monte, un projectile qui part.
#
#  Aucune fonction ici : uniquement des boucles dans des blocs
#  d'événement.
#
#  -------------------------------------------------------------------
#  Où trouver les noms
#  -------------------------------------------------------------------
#
#  Les événements se découvrent dans le jeu. Mettre la partie en pause
#  avec Échap, puis survoler le vaisseau : la rubrique « RÉPÉTITIONS
#  dans student_loops.py » donne le nom exact de chaque événement, son
#  effet et les valeurs fournies dans le bloc.
#
#  -------------------------------------------------------------------
#  En cas d'erreur
#  -------------------------------------------------------------------
#
#  Une boucle fautive ne bloque jamais le jeu : le jeu l'arrête et
#  affiche le problème dans un bandeau rouge en bas de l'écran. Une
#  boucle qui ne s'arrête jamais est coupée au bout de 1000 tours.
# =====================================================================
